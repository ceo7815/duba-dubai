export function optionLabel(value: string, lang: Lang) {
  if (lang === "en") return value.trim();
  return optionHe[value.trim().toLowerCase()] ?? value.trim();
}

export function nameOf(item: { title: string; he: string }, lang: Lang) {
  return lang === "he" && item.he ? item.he : item.title;
}

export function aed(value: number) {
  return `${new Intl.NumberFormat("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(value)} AED`;
}
